CREATE TABLE IF NOT EXISTS savings_entry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, circle_id BIGINT NOT NULL REFERENCES savings_circle(id),
 kind VARCHAR(15) NOT NULL, amount DECIMAL(14,2) NOT NULL CHECK(amount>0), member_id BIGINT,
 actual_date DATE NOT NULL, note VARCHAR(500) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 FOREIGN KEY(circle_id,member_id) REFERENCES circle_member(circle_id,user_id),
 CHECK(kind IN ('CONTRIBUTION','EXPENSE','WITHDRAWAL')),
 CHECK(kind<>'CONTRIBUTION' OR member_id IS NOT NULL)
);
