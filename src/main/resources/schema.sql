CREATE TABLE IF NOT EXISTS app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS loan (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lender_id BIGINT NOT NULL REFERENCES app_user(id), borrower_id BIGINT NOT NULL REFERENCES app_user(id),
 initiator_id BIGINT NOT NULL REFERENCES app_user(id), status VARCHAR(30) NOT NULL,
 current_version INT NOT NULL, completed_on DATE,
 CHECK(lender_id <> borrower_id),
 CHECK(status IN ('PENDING_TERMS','AWAITING_HANDOVER','ACTIVE','COMPLETED','DECLINED','CANCELLED'))
);
CREATE TABLE IF NOT EXISTS loan_terms (
 loan_id BIGINT NOT NULL REFERENCES loan(id), version INT NOT NULL,
 kind VARCHAR(10) NOT NULL, amount DECIMAL(14,2), currency VARCHAR(3), item_description VARCHAR(200),
 start_date DATE NOT NULL, due_date DATE NOT NULL, proposed_by BIGINT NOT NULL REFERENCES app_user(id),
 PRIMARY KEY(loan_id,version), CHECK(start_date <= due_date),
 CHECK((kind='MONEY' AND amount>0 AND currency IS NOT NULL AND item_description IS NULL) OR
       (kind='ITEM' AND amount IS NULL AND currency IS NULL AND item_description IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS loan_confirmation (
 loan_id BIGINT NOT NULL, version INT NOT NULL, user_id BIGINT NOT NULL REFERENCES app_user(id),
 confirmed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
 PRIMARY KEY(loan_id,version,user_id), FOREIGN KEY(loan_id,version) REFERENCES loan_terms(loan_id,version)
);
CREATE TABLE IF NOT EXISTS loan_activity (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 loan_id BIGINT NOT NULL, version INT NOT NULL, kind VARCHAR(20) NOT NULL,
 submitted_by BIGINT NOT NULL REFERENCES app_user(id), actual_date DATE NOT NULL, amount DECIMAL(14,2),
 note VARCHAR(500) NOT NULL, status VARCHAR(25) NOT NULL DEFAULT 'PENDING_REVIEW',
 reviewed_by BIGINT REFERENCES app_user(id), review_reason VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL, reviewed_at TIMESTAMP WITH TIME ZONE,
 FOREIGN KEY(loan_id,version) REFERENCES loan_terms(loan_id,version),
 CHECK(kind IN ('HANDOVER','REPAYMENT','ITEM_RETURN')),
 CHECK(status IN ('PENDING_REVIEW','CONFIRMED','DISPUTED','WITHDRAWN')),
 CHECK(reviewed_by IS NULL OR reviewed_by<>submitted_by)
);
CREATE TABLE IF NOT EXISTS receipt (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 activity_id BIGINT NOT NULL UNIQUE REFERENCES loan_activity(id),
 content_type VARCHAR(20) NOT NULL, content BINARY LARGE OBJECT NOT NULL
);
CREATE TABLE IF NOT EXISTS notification (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient_id BIGINT NOT NULL REFERENCES app_user(id), loan_id BIGINT REFERENCES loan(id),
 message VARCHAR(500) NOT NULL, dedup_key VARCHAR(200) NOT NULL UNIQUE,
 is_read BOOLEAN DEFAULT FALSE NOT NULL, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS savings_circle (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL, organiser_id BIGINT NOT NULL REFERENCES app_user(id), currency VARCHAR(3) NOT NULL,
 target_amount DECIMAL(14,2), contribution_amount DECIMAL(14,2), frequency VARCHAR(10),
 start_date DATE, status VARCHAR(10) DEFAULT 'ACTIVE' NOT NULL
);
CREATE TABLE IF NOT EXISTS circle_member (
 circle_id BIGINT NOT NULL REFERENCES savings_circle(id), user_id BIGINT NOT NULL REFERENCES app_user(id),
 joined_on DATE DEFAULT CURRENT_DATE NOT NULL,
 PRIMARY KEY(circle_id,user_id)
);
